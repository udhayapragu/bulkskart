function inside(poly, lon, lat) {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}

const landPolys = Object.values(LAND);
const waterPolys = Object.values(WATER);
const dots = [];
for (let row = 0, y = STEP / 2; y < MAP_H; row += 1, y += STEP) {
  const offset = row % 2 === 0 ? STEP / 2 : STEP;
  for (let x = offset; x < MAP_W; x += STEP) {
    const [lon, lat] = unproject(x, y);
    if (landPolys.some((p) => inside(p, lon, lat)) && !waterPolys.some((p) => inside(p, lon, lat))) {
      dots.push([x, y]);
    }
  }
}

const path = dots.map(([x, y]) => `M${x} ${y}h0`).join('');
const out = `// Generated by scripts/generate-world-dots.mjs. Do not edit by hand.
// Dotted world map drawn from simplified continent outlines (about 3 degrees accuracy).
export const MAP_WIDTH = ${MAP_W};
export const MAP_HEIGHT = ${MAP_H};
export const MAP_LAT_TOP = ${LAT_TOP};
export const MAP_LAT_BOTTOM = ${LAT_BOTTOM};
export const WORLD_DOT_COUNT = ${dots.length};
export const WORLD_DOTS_PATH = '${path}';
`;
writeFileSync(new URL('../src/data/worldDots.ts', import.meta.url), out);
